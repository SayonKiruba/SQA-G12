
#!/usr/bin/env bash
# ============================================================
# SQA Group 12 - Automated Test Execution
#
# Runs Phase01 test cases against the Phase03 C++ frontend.
# Saves terminal outputs, transaction files, and exit codes
# for comparison using check_outputs.sh.
#
# Usage (from project root): bash Phase03/run_tests.sh
# ============================================================

set -euo pipefail

# Define the project directories used for testing.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
TESTS_DIR="$PROJECT_ROOT/Phase01/tests"
WORK_DIR="$SCRIPT_DIR/.test-work"
RESULTS_DIR="$SCRIPT_DIR/test-results"

# Check the arguments and make sure the required test data exists.
if [ "$#" -gt 1 ]; then
    echo "Usage: bash Phase03/run_tests.sh [path/to/compiled/program]" >&2
    exit 2
fi

if [ ! -d "$TESTS_DIR/data" ]; then
    echo "Missing test data: $TESTS_DIR/data" >&2
    exit 1
fi

# Clear previous temporary outputs and prepare the test directories.
rm -rf "$WORK_DIR"
mkdir -p "$WORK_DIR" "$RESULTS_DIR"

# Compile the C++ frontend before running the test cases.
if [ "$#" -eq 1 ]; then
    PROGRAM="$1"
    if [ ! -x "$PROGRAM" ]; then
        echo "Program not executable: $PROGRAM" >&2
        exit 1
    fi
else
    if ! command -v g++ >/dev/null 2>&1; then
        echo "g++ not found. Install g++ or pass a compiled program." >&2
        exit 1
    fi

    PROGRAM="$WORK_DIR/SQA_G12.exe"
    echo "Compiling the C++ application..."

    g++ -std=c++14 -I"$PROJECT_ROOT/Phase03/Frontend" \
        "$PROJECT_ROOT/Phase03/Frontend/main.cpp" \
        "$PROJECT_ROOT/Phase03/Frontend/FrontEnd.cpp" \
        "$PROJECT_ROOT/Phase03/Frontend/TransactionManager.cpp" \
        "$PROJECT_ROOT/Phase03/Frontend/FileManager.cpp" \
        "$PROJECT_ROOT/Phase03/Frontend/User.cpp" \
        -o "$PROGRAM"
fi

# Run each Phase01 test case and track any execution errors.
count=0
errors=0

for input_file in "$TESTS_DIR"/*/*/input.txt; do
    [ -f "$input_file" ] || continue

    case_dir="$(dirname "$input_file")"
    relative_case="${case_dir#"$TESTS_DIR"/}"
    case_work="$WORK_DIR/$relative_case"

    mkdir -p "$case_work/data"

    # Give each test a fresh copy of the data to keep tests independent.
    cp "$TESTS_DIR"/data/*.txt "$case_work/data/"

    # Define the output files generated by this test.
    actual_output="$case_work/actual_output.txt"
    transaction_output="$case_work/actual_transactions.atf"

    # Run the program and save terminal output, transactions,
    # error messages, and exit status for comparison.
    exit_code=0

    "$PROGRAM" "$case_work/data" "$transaction_output" \
        < "$input_file" > "$actual_output" \
        2> "$case_work/stderr.txt" || exit_code=$?

    printf '%s\n' "$exit_code" > "$case_work/exit_code.txt"

    if [ "$exit_code" -ne 0 ]; then
        errors=$((errors + 1))
    fi

    count=$((count + 1))
done

# Make sure at least one test case was found and executed.
if [ "$count" -eq 0 ]; then
    echo "No test cases found under Phase01/tests." >&2
    exit 1
fi

# Display the execution summary and the next step for checking results.
echo ""
echo "Test Execution Summary"
echo "Total executed: $count"
echo "Execution errors: $errors"
echo ""
echo "Now run: bash Phase03/check_outputs.sh"
